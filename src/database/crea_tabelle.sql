-- =====================================================================
-- TheKnife - Creazione delle tabelle del database (PostgreSQL)
-- Traduzione dello schema logico:
--   Utenti(username, nome, cognome, password, data_nascita*, indirizzo, citta, ruolo)
--   RistorantiTheKnife(id, nome, nazione, citta, indirizzo, latitudine, longitudine,
--                      fascia, delivery, prenotazione_online, proprietario*)
--   Cucine(nome)
--   RistorantiCucine(ristorante, cucina)
--   Recensioni(cliente, ristorante, stelle, testo*, risposta*)
--   Preferiti(cliente, ristorante)
-- Le tabelle sono create in ordine: prima quelle a cui puntano le chiavi esterne.
-- =====================================================================

-- Cancella le tabelle esistenti, cosi' lo script crea il database da zero.
DROP TABLE IF EXISTS Preferiti, Recensioni, RistorantiCucine, Cucine, RistorantiTheKnife, Utenti CASCADE;


-- Utenti registrati: clienti e ristoratori.
CREATE TABLE Utenti (
    username     VARCHAR(30)  PRIMARY KEY,           -- distingue maiuscole e minuscole
    nome         VARCHAR(50)  NOT NULL,
    cognome      VARCHAR(50)  NOT NULL,
    password     VARCHAR(100) NOT NULL,              -- salvata cifrata (hash), mai in chiaro
    data_nascita DATE,                               -- facoltativa
    indirizzo    VARCHAR(100) NOT NULL,              -- domicilio: indirizzo
    citta        VARCHAR(60)  NOT NULL,              -- domicilio: citta
    ruolo        VARCHAR(11)  NOT NULL
                 CHECK (ruolo IN ('cliente', 'ristoratore'))
);


-- Ristoranti: quelli del file iniziale (senza proprietario) e quelli inseriti dai ristoratori.
CREATE TABLE RistorantiTheKnife (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(100) NOT NULL,
    nazione             VARCHAR(60)  NOT NULL,
    citta               VARCHAR(60)  NOT NULL,
    indirizzo           VARCHAR(200) NOT NULL,
    latitudine          NUMERIC(9,6) NOT NULL CHECK (latitudine BETWEEN -90 AND 90),
    longitudine         NUMERIC(9,6) NOT NULL CHECK (longitudine BETWEEN -180 AND 180),
    fascia              SMALLINT     NOT NULL CHECK (fascia BETWEEN 1 AND 4),  -- 1 = €, 4 = €€€€
    delivery            BOOLEAN      NOT NULL,
    prenotazione_online BOOLEAN      NOT NULL,
    proprietario        VARCHAR(30)  REFERENCES Utenti(username) ON DELETE CASCADE,  -- facoltativo
    UNIQUE (nome, nazione, citta, indirizzo)         -- stesso nome e stessa ubicazione: non ammesso
);


-- Elenco dei tipi di cucina, ognuno scritto una volta sola.
CREATE TABLE Cucine (
    nome VARCHAR(50) PRIMARY KEY
);


-- Tipi di cucina offerti da ogni ristorante (associazione Offre).
CREATE TABLE RistorantiCucine (
    ristorante INTEGER     NOT NULL REFERENCES RistorantiTheKnife(id) ON DELETE CASCADE,
    cucina     VARCHAR(50) NOT NULL REFERENCES Cucine(nome),
    PRIMARY KEY (ristorante, cucina)
);


-- Recensioni dei clienti, con l'eventuale risposta del proprietario del ristorante.
CREATE TABLE Recensioni (
    cliente    VARCHAR(30) NOT NULL REFERENCES Utenti(username) ON DELETE CASCADE,
    ristorante INTEGER     NOT NULL REFERENCES RistorantiTheKnife(id) ON DELETE CASCADE,
    stelle     SMALLINT    NOT NULL CHECK (stelle BETWEEN 1 AND 5),
    testo      VARCHAR(250),                         -- facoltativo
    risposta   VARCHAR(250),                         -- facoltativa
    PRIMARY KEY (cliente, ristorante)                -- al massimo una recensione per cliente e ristorante
);


-- Liste dei preferiti dei clienti.
CREATE TABLE Preferiti (
    cliente    VARCHAR(30) NOT NULL REFERENCES Utenti(username) ON DELETE CASCADE,
    ristorante INTEGER     NOT NULL REFERENCES RistorantiTheKnife(id) ON DELETE CASCADE,
    PRIMARY KEY (cliente, ristorante)                -- un ristorante al massimo una volta per lista
);
